CREATE TABLE roluri (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume VARCHAR(30) NOT NULL UNIQUE,
    descriere VARCHAR(255),

    CONSTRAINT chk_roluri_nume
        CHECK (nume IN ('ADMIN', 'RECEPTIONIST', 'MANAGER'))
);

CREATE TABLE utilizatori (
    id_utilizator BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume_complet VARCHAR(100) NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    parola_hash VARCHAR(255) NOT NULL,
    activ BOOLEAN NOT NULL DEFAULT TRUE,
    data_crearii TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_rol BIGINT NOT NULL,

    CONSTRAINT fk_utilizatori_roluri
        FOREIGN KEY (id_rol)
        REFERENCES roluri(id_rol)
        ON DELETE RESTRICT
);

CREATE TABLE clienti (
    id_client BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume VARCHAR(100) NOT NULL,
    prenume VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE,
    telefon VARCHAR(20),
    data_crearii TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE camere (
    id_camera BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numar_camera VARCHAR(10) NOT NULL UNIQUE,
    tip VARCHAR(30) NOT NULL,
    pret_noapte NUMERIC(10, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'LIBERA',

    CONSTRAINT chk_camere_tip
        CHECK (tip IN ('SINGLE', 'DOUBLE', 'TWIN', 'SUITE')),

    CONSTRAINT chk_camere_pret
        CHECK (pret_noapte > 0),

    CONSTRAINT chk_camere_status
        CHECK (status IN ('LIBERA', 'OCUPATA', 'MENTENANTA'))
);

CREATE TABLE rezervari (
    id_rezervare BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_client BIGINT NOT NULL,
    id_camera BIGINT NOT NULL,
    data_checkin DATE NOT NULL,
    data_checkout DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMATA',
    data_crearii TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_rezervari_clienti
        FOREIGN KEY (id_client)
        REFERENCES clienti(id_client)
        ON DELETE RESTRICT,

    CONSTRAINT fk_rezervari_camere
        FOREIGN KEY (id_camera)
        REFERENCES camere(id_camera)
        ON DELETE RESTRICT,

    CONSTRAINT chk_rezervari_date
        CHECK (data_checkout > data_checkin),

    CONSTRAINT chk_rezervari_status
        CHECK (status IN ('IN_ASTEPTARE', 'CONFIRMATA', 'ANULATA', 'FINALIZATA'))
);

CREATE TABLE plati (
    id_plata BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rezervare BIGINT NOT NULL,
    suma NUMERIC(10, 2) NOT NULL,
    metoda VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_ASTEPTARE',
    data_platii TIMESTAMP,

    CONSTRAINT fk_plati_rezervari
        FOREIGN KEY (id_rezervare)
        REFERENCES rezervari(id_rezervare)
        ON DELETE RESTRICT,

    CONSTRAINT chk_plati_suma
        CHECK (suma > 0),

    CONSTRAINT chk_plati_metoda
        CHECK (metoda IN ('CASH', 'CARD', 'TRANSFER')),

    CONSTRAINT chk_plati_status
        CHECK (status IN ('IN_ASTEPTARE', 'ACHITATA', 'ESUATA', 'RAMBURSATA'))
);